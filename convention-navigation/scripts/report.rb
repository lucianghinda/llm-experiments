#!/usr/bin/env ruby
# frozen_string_literal: true

# Builds the tables that go into RESULTS.md.
#
#   ruby convention-navigation/scripts/report.rb
#   ruby convention-navigation/scripts/report.rb --write   # also write results/tables.md
#
# metrics.rb is for reading at a terminal while deciding what happened. This is
# for producing the numbers that get published, so that no figure in RESULTS.md
# is ever typed by hand. A transcribed median is a median nobody can re-derive,
# and this repository's whole point is that a claim can be re-run.
#
# Every table here obeys the same three rules as metrics.rb: never pool across
# agents, never pool across tasks, and count only trials that passed. Failure
# rates get their own table, because a condition that saves tokens by giving up
# has not saved anything.

require "json"
require "fileutils"
require_relative "lib/stats"

EXPERIMENT_DIR = File.expand_path("..", __dir__)

CONDITIONS = %w[conventional scrambled scrambled-mapped conventional-mapped].freeze

# The four that answer the question. total_input_tokens is the headline; the
# other three are the mechanism, and they are what tell a real effect apart from
# a coincidence in token accounting.
HEADLINE = {
  "total_input_tokens" => "input tokens",
  "total_tool_calls" => "tool calls",
  "search_calls" => "search calls",
  "distinct_files_read" => "files read"
}.freeze

# The map condition gets one extra metric. `searches_before_first_target` is the
# count the map is supposed to act on directly -- a document saying where models
# live should cut the searching that happens before the first one is opened -- so
# it is the metric that says whether a recovery is the map working or a
# coincidence in token accounting.
MAP_METRICS = HEADLINE.merge(
  "searches_before_first_target" => "searches before first target"
).freeze

# Derived from the trial directory rather than from the transcript: how much
# code the agent wrote to reach its passing state. Cost has two currencies and
# tokens are only one of them -- two trials that pass the same acceptance check
# can differ by a factor of seven in the code they leave behind.
#
# `diff_added_lines` counts `+` lines in agent.diff, excluding file headers.
# agent.diff is `git diff` over tracked files, so brand-new files -- the
# migration, a new test file -- contribute nothing to the line count; their
# contents are not kept. They are counted in `files_touched`, which is modified
# plus untracked files from meta.json.
DIFF_METRICS = {
  "diff_added_lines" => "lines added to tracked files",
  "files_touched" => "files touched (modified + new)"
}.freeze

def commas(number)
  return "-" if number.nil?

  whole = number.round
  whole.to_s.reverse.scan(/\d{1,3}/).join(",").reverse
end

raw = Dir.glob(File.join(EXPERIMENT_DIR, "results-raw", "**", "metrics.json"))
files = raw.empty? ? Dir.glob(File.join(EXPERIMENT_DIR, "results", "**", "metrics.json")) : raw
abort "no metrics.json found. Run trials, then parse_transcript.rb --all" if files.empty?

# Each record is a metrics.json enriched with the two DIFF_METRICS, read from
# the same trial directory. Every trial has an agent.diff (empty when the agent
# changed nothing, which is every locate trial) and a meta.json with both file
# lists, so a nil here means the directory is broken, not that the trial is old.
all = files.map do |f|
  record = JSON.parse(File.read(f))
  dir = File.dirname(f)
  diff_path = File.join(dir, "agent.diff")
  if File.exist?(diff_path)
    record["diff_added_lines"] =
      File.foreach(diff_path).count { |l| l.start_with?("+") && !l.start_with?("+++") }
  end
  meta_path = File.join(dir, "meta.json")
  if File.exist?(meta_path)
    meta = JSON.parse(File.read(meta_path))
    record["files_touched"] = (meta["changed_files"] || []).size + (meta["untracked_files"] || []).size
  end
  record
end
passed = all.select { |r| r["passed"] }

agents = all.map { |r| r["agent"] }.uniq.compact.sort
tasks = all.map { |r| r["task"] }.uniq.compact.sort
present_conditions = CONDITIONS.select { |c| all.any? { |r| r["condition"] == c } }

out = +""
out << "# Tables\n\n"
out << "Generated by `scripts/report.rb`. Do not edit: re-run it instead, so\n"
out << "every number here stays something that can be re-derived from the trials.\n\n"
out << "#{all.size} trial(s), of which #{passed.size} passed and are counted below.\n"
out << "Failures are never counted toward cost; they get their own table.\n\n"

# --- per agent, per metric ----------------------------------------------------
agents.each do |agent|
  out << "## #{agent}\n\n"

  HEADLINE.each do |metric, label|
    out << "### #{label}, median over trials that passed\n\n"
    # The change and p columns are conventional-to-scrambled and stay that way
    # even when a third condition has a column, because that pair is the
    # pre-registered question. The map's comparisons get their own table.
    out << "| task | " + present_conditions.join(" | ") + " | change c->s | exact p c->s |\n"
    out << "|---" * (present_conditions.size + 3) + "|\n"

    tasks.each do |task|
      cell = passed.select { |r| r["agent"] == agent && r["task"] == task }
      next if cell.empty?

      medians = present_conditions.to_h do |cond|
        values = cell.select { |r| r["condition"] == cond }.filter_map { |r| r[metric] }.map(&:to_f)
        [cond, values.empty? ? nil : Stats.median(values)]
      end

      base = medians["conventional"]
      scrambled = medians["scrambled"]
      change =
        if base && scrambled
          pct = Stats.percent_change(base, scrambled)
          pct ? format("%+.0f%%", pct) : format("%+.1f", scrambled - base)
        else
          "-"
        end

      a = cell.select { |r| r["condition"] == "conventional" }.filter_map { |r| r[metric] }.map(&:to_f)
      b = cell.select { |r| r["condition"] == "scrambled" }.filter_map { |r| r[metric] }.map(&:to_f)
      p_text =
        if a.empty? || b.empty?
          "-"
        else
          result = Stats.exact_mann_whitney(a, b)
          result[:p] ? format("%.3f", result[:p]) : result[:note]
        end

      cells = present_conditions.map do |cond|
        value = medians[cond]
        next "-" if value.nil?

        metric == "total_input_tokens" ? commas(value) : format("%g", value.round(1))
      end

      out << "| #{task} | #{cells.join(' | ')} | #{change} | #{p_text} |\n"
    end
    out << "\n"
  end
end

# --- the pre-registered rule --------------------------------------------------
out << "## Direction across tasks: conventional to scrambled\n\n"
out << "This is the pre-registered question. A real effect should push the same\n"
out << "way on every task; the per-task p-values above ask whether any single\n"
out << "task separates, which is a different and weaker thing to ask.\n\n"
out << "| agent | metric | scrambled higher on | ties | sign test p |\n"
out << "|---|---|---|---|---|\n"

agents.each do |agent|
  HEADLINE.each do |metric, label|
    wins = 0
    losses = 0
    ties = 0
    tasks.each do |task|
      cell = passed.select { |r| r["agent"] == agent && r["task"] == task }
      a = cell.select { |r| r["condition"] == "conventional" }.filter_map { |r| r[metric] }.map(&:to_f)
      b = cell.select { |r| r["condition"] == "scrambled" }.filter_map { |r| r[metric] }.map(&:to_f)
      next if a.empty? || b.empty?

      delta = Stats.median(b) - Stats.median(a)
      if delta.positive? then wins += 1
      elsif delta.negative? then losses += 1
      else ties += 1
      end
    end
    next if wins + losses + ties == 0

    test = Stats.sign_test(wins, losses)
    p_text = test[:p] ? format("%.3f", test[:p]) : test[:note]
    out << "| #{agent} | #{label} | #{wins}/#{wins + losses} task(s) | #{ties} | #{p_text} |\n"
  end
end
out << "\n"

# --- the map --------------------------------------------------------------
#
# Three comparisons, each answering something the others cannot.
#
#   conv -> conv+map   what a document buys when it says only what an agent
#                      could already have guessed. This is the control: it holds
#                      "there is a document" constant and takes away the only
#                      thing the scrambled map had to tell you.
#   scr  -> scr+map    what a document buys when the layout is unguessable.
#                      The question the follow-up was built to ask.
#   conv+map -> scr+map  with a document on both sides, does the layout still
#                      cost anything? This is the only clean way to ask whether
#                      a documented nonstandard layout can match a conventional
#                      one, and it exists because conv -> scr+map cannot: that
#                      pair varies the layout and the document together.
#
# Each layout is described by its own map, truthfully. The conventional one is
# shorter because there is less to say, and that asymmetry is a property of the
# thing being measured rather than a flaw in the measurement: a conventional
# layout needs less documentation. Byte counts are printed so a reader can weigh
# it.
if present_conditions.include?("scrambled-mapped")
  out << "## The map: what a document saying where things live is worth\n\n"
  out << "Each layout carries its own map, describing that layout truthfully.\n"
  out << "`conv+map` is the control for `scr+map`: it holds the presence of an\n"
  out << "agent-instruction file constant and removes only the thing the scrambled\n"
  out << "map had to tell you, since a conventional layout's map mostly restates\n"
  out << "Rails defaults. Change is shown with its exact p in brackets.\n\n"
  out << "| agent | metric | conv | conv+map | scr | scr+map | conv -> conv+map | scr -> scr+map | conv+map -> scr+map |\n"
  out << "|---|---|---|---|---|---|---|---|---|\n"

  agents.each do |agent|
    MAP_METRICS.merge(DIFF_METRICS).each do |metric, label|
      tasks.each do |task|
        cell = passed.select { |r| r["agent"] == agent && r["task"] == task }
        series = CONDITIONS.to_h do |cond|
          [cond, cell.select { |r| r["condition"] == cond }.filter_map { |r| r[metric] }.map(&:to_f)]
        end
        # The three-condition core must be present; conventional-mapped may not
        # be, so the table still renders before that arm has run.
        next if %w[conventional scrambled scrambled-mapped].any? { |c| series[c].empty? }

        med = series.transform_values { |v| v.empty? ? nil : Stats.median(v) }
        show = lambda do |value|
          next "-" if value.nil?

          metric == "total_input_tokens" ? commas(value) : format("%g", value.round(1))
        end

        pair = lambda do |from, to|
          next "-" if med[from].nil? || med[to].nil?

          pct = Stats.percent_change(med[from], med[to])
          delta = pct ? format("%+.0f%%", pct) : format("%+.1f", med[to] - med[from])
          result = Stats.exact_mann_whitney(series[from], series[to])
          "#{delta} (#{result[:p] ? format('%.3f', result[:p]) : result[:note]})"
        end

        out << "| #{agent} | #{label} | " \
               "#{show.call(med['conventional'])} | #{show.call(med['conventional-mapped'])} | " \
               "#{show.call(med['scrambled'])} | #{show.call(med['scrambled-mapped'])} | " \
               "#{pair.call('conventional', 'conventional-mapped')} | " \
               "#{pair.call('scrambled', 'scrambled-mapped')} | " \
               "#{pair.call('conventional-mapped', 'scrambled-mapped')} |\n"
      end
    end
  end
  out << "\n"
end

# --- code written -------------------------------------------------------------
out << "## Code written\n\n"
out << "How much code each passing trial left behind. Lines are `+` lines in\n"
out << "agent.diff, which is `git diff` over tracked files -- a brand-new file\n"
out << "(the migration, a fresh test file) adds nothing to the line count and is\n"
out << "counted only in files touched. Two trials that pass the same scripted\n"
out << "acceptance check can differ by a factor of seven here, and nothing in\n"
out << "this experiment scores which of them wrote the better change: passing is\n"
out << "the only quality bar a trial faces.\n\n"

agents.each do |agent|
  DIFF_METRICS.each do |metric, label|
    out << "### #{agent}: #{label}, median over trials that passed\n\n"
    out << "| task | " + present_conditions.join(" | ") + " | change c->s | exact p c->s |\n"
    out << "|---" * (present_conditions.size + 3) + "|\n"

    tasks.each do |task|
      cell = passed.select { |r| r["agent"] == agent && r["task"] == task }
      next if cell.empty?

      medians = present_conditions.to_h do |cond|
        values = cell.select { |r| r["condition"] == cond }.filter_map { |r| r[metric] }.map(&:to_f)
        [cond, values.empty? ? nil : Stats.median(values)]
      end

      a = cell.select { |r| r["condition"] == "conventional" }.filter_map { |r| r[metric] }.map(&:to_f)
      b = cell.select { |r| r["condition"] == "scrambled" }.filter_map { |r| r[metric] }.map(&:to_f)
      change =
        if medians["conventional"] && medians["scrambled"]
          pct = Stats.percent_change(medians["conventional"], medians["scrambled"])
          pct ? format("%+.0f%%", pct) : format("%+.1f", medians["scrambled"] - medians["conventional"])
        else
          "-"
        end
      p_text =
        if a.empty? || b.empty?
          "-"
        else
          result = Stats.exact_mann_whitney(a, b)
          result[:p] ? format("%.3f", result[:p]) : result[:note]
        end

      cells = present_conditions.map { |cond| medians[cond].nil? ? "-" : format("%g", medians[cond].round(1)) }
      out << "| #{task} | #{cells.join(' | ')} | #{change} | #{p_text} |\n"
    end
    out << "\n"
  end
end

# --- zero-search navigation ---------------------------------------------------
out << "## Zero-search navigation\n\n"
out << "How often the agent reached a file it needed without a single grep, glob\n"
out << "or find beforehand. This is what \"the model already knows where to look\"\n"
out << "means, phrased so a transcript can answer it, and it does not depend on\n"
out << "token accounting at all. Trials that never reached a target are excluded\n"
out << "rather than counted as false: \"went straight there\" is not a claim you\n"
out << "can make about a trial that never got there.\n\n"
out << "| agent | task | " + present_conditions.join(" | ") + " |\n"
out << "|---" * (present_conditions.size + 2) + "|\n"

agents.each do |agent|
  tasks.each do |task|
    cell = all.select { |r| r["agent"] == agent && r["task"] == task && !r["zero_search_navigation"].nil? }
    next if cell.empty?

    cells = present_conditions.map do |cond|
      subset = cell.select { |r| r["condition"] == cond }
      next "-" if subset.empty?

      "#{subset.count { |r| r['zero_search_navigation'] }}/#{subset.size}"
    end
    out << "| #{agent} | #{task} | #{cells.join(' | ')} |\n"
  end
end
out << "\n"

# --- outcomes -----------------------------------------------------------------
out << "## Trials that passed\n\n"
out << "Charged separately from cost, and never folded into it. A condition that\n"
out << "spends fewer tokens by failing more has not saved anything, and a higher\n"
out << "failure rate under scrambled would support the hypothesis more strongly\n"
out << "than any token difference.\n\n"
out << "| agent | task | " + present_conditions.join(" | ") + " |\n"
out << "|---" * (present_conditions.size + 2) + "|\n"

agents.each do |agent|
  tasks.each do |task|
    cell = all.select { |r| r["agent"] == agent && r["task"] == task }
    next if cell.empty?

    cells = present_conditions.map do |cond|
      subset = cell.select { |r| r["condition"] == cond }
      next "-" if subset.empty?

      "#{subset.count { |r| r['passed'] }}/#{subset.size}"
    end
    out << "| #{agent} | #{task} | #{cells.join(' | ')} |\n"
  end
end
out << "\n"

# --- spread -------------------------------------------------------------------
#
# Published because a median over five noisy runs deserves to be shown with the
# runs behind it. Anyone should be able to see whether a difference is a shift
# or two overlapping clouds.
out << "## Every input-token measurement behind the medians\n\n"
out << "| agent | task | condition | n | values |\n"
out << "|---|---|---|---|---|\n"
agents.each do |agent|
  tasks.each do |task|
    present_conditions.each do |cond|
      values = passed.select { |r| r["agent"] == agent && r["task"] == task && r["condition"] == cond }
                     .filter_map { |r| r["total_input_tokens"] }.sort
      next if values.empty?

      out << "| #{agent} | #{task} | #{cond} | #{values.size} | #{values.map { |v| commas(v) }.join(', ')} |\n"
    end
  end
end
out << "\n"

puts out

if ARGV.include?("--write")
  dest = File.join(EXPERIMENT_DIR, "results")
  FileUtils.mkdir_p(dest)
  File.write(File.join(dest, "tables.md"), out)
  warn "[report] wrote #{File.join(dest, 'tables.md').sub(EXPERIMENT_DIR + '/', '')}"
end
