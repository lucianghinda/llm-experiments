#!/usr/bin/env ruby
# frozen_string_literal: true

# Turns results/*.json into results/tables.md.
#
#   ruby word-vector-arithmetic/scripts/report.rb
#   ruby word-vector-arithmetic/scripts/report.rb --stdout   # print, write nothing
#
# EVERY NUMBER IN README.md COMES FROM HERE. Nothing is counted by hand, so a
# claim in the write-up can be re-derived by rerunning this file against the
# committed JSON -- no download, no rescan.
#
# TWO COLUMNS ARE THE WHOLE POINT OF THE ANALOGY TABLE. The same items are
# scored with the three input words excluded from the ranking and with them left
# in. The first is what gensim's most_similar reports and what the famous claim
# rests on; the second is where the arithmetic actually lands. They are printed
# side by side and never averaged together.
#
# MODELS ARE COMPARED ON SHARED ITEMS ONLY. GPT-2 has no single token for
# geese, oxen, cacti or cactus, so three plural pairs exist for GloVe and not
# for GPT-2. Comparing 30 pairs against 27 would credit GloVe for questions
# GPT-2 was never asked, so the comparison table intersects first and says how
# many items survived.
#
# TOKENS ARE PRINTED WITH THEIR QUOTES. " queen" and "queen" are different rows
# of GPT-2's embedding matrix, and a markdown code span eats a leading space, so
# every token is rendered inspected rather than bare.

require "json"

EXPERIMENT_DIR = File.expand_path("..", __dir__)
RESULTS = File.join(EXPERIMENT_DIR, "results")
METRICS = %w[euclidean cosine].freeze
CONDITIONS = %w[seed averaged].freeze
DIRECTION_METRICS = %w[dot cosine].freeze

def pct(hits, total)
  return "n/a" if total.zero?

  format("%d/%d (%d%%)", hits, total, (100.0 * hits / total).round)
end

def median(values)
  values = values.compact
  return "n/a" if values.empty?

  sorted = values.sort
  middle = sorted.length / 2
  value = sorted.length.odd? ? sorted[middle] : ((sorted[middle - 1] + sorted[middle]) / 2.0)
  format("%g", value)
end

def show(token)
  token.nil? ? "-" : "`#{token.inspect}`"
end

def table(headers, rows)
  lines = ["| #{headers.join(" | ")} |", "|#{headers.map { "---" }.join("|")}|"]
  rows.each { |row| lines << "| #{row.join(" | ")} |" }
  "#{lines.join("\n")}\n"
end

models = %w[glove gpt2].select { |m| File.exist?(File.join(RESULTS, "analogy-#{m}.json")) }
abort "no results to report" if models.empty?

analogy = models.to_h { |m| [m, JSON.parse(File.read(File.join(RESULTS, "analogy-#{m}.json")))] }
direction = models.to_h { |m| [m, JSON.parse(File.read(File.join(RESULTS, "direction-#{m}.json")))] }
key = ->(row) { row.values_at("a", "b", "c", "expected") }
pair_key = ->(row) { row.values_at("singular", "plural") }

# The ruby group asks a different question (programming senses of polysemous
# words), so no table below ever mixes it with the original analogies.
core = models.to_h { |m| [m, analogy[m]["analogies"].reject { |r| r["group"] == "ruby" }] }
ruby = models.to_h { |m| [m, analogy[m]["analogies"].select { |r| r["group"] == "ruby" }] }

out = +""
out << "<!-- Generated by scripts/report.rb. Do not edit by hand. -->\n\n"
out << "# Tables\n\n"

out << table(
  ["model", "entries", "dimensions", "candidate pool", "analogies", "ruby analogies", "plural pairs"],
  models.map do |m|
    p = analogy[m]["provenance"]
    [m, p["vocabulary"], p["dimensions"], p["candidate_pool"] || "whole vocabulary",
     core[m].length, ruby[m].length, direction[m]["pairs"].length]
  end
)

out << "\n## 1. Analogy top-1 accuracy\n\n"
out << "`b - a + c`, ranked against the vocabulary. A hit means the expected "
out << "word came first. \"word-like only\" restricts GPT-2's candidates to "
out << "whole words as they appear mid-sentence, since most of its vocabulary "
out << "is fragments that no GloVe ranking could return.\n\n"
out << table(
  ["model", "metric", "inputs excluded", "inputs kept", "word-like only", "median rank excl."],
  models.flat_map do |m|
    METRICS.map do |metric|
      scored = core[m].map { |r| r[metric] }
      word_like = scored.map { |s| s["rank_word_like"] }.compact
      [m, metric,
       pct(scored.count { |s| s["rank"] == 1 }, scored.length),
       pct(scored.count { |s| s["rank_with_inputs"] == 1 }, scored.length),
       word_like.empty? ? "-" : pct(word_like.count { |r| r == 1 }, word_like.length),
       median(scored.map { |s| s["rank"] })]
    end
  end
)

out << "\n## 2. What comes first when the inputs are left in\n\n"
out << "The three input words are `a`, `b`, `c`. If the nearest point to "
out << "`b - a + c` is one of them, the arithmetic did not move far enough to "
out << "leave its own inputs behind.\n\n"
out << table(
  ["model", "metric", "an input word", "the expected word", "something else"],
  models.flat_map do |m|
    rows = core[m]
    METRICS.map do |metric|
      tally = rows.map do |r|
        top = r[metric]["top1_with_inputs"]
        inputs = r["tokens"] ? r["tokens"].values_at(r["a"], r["b"], r["c"]) : [r["a"], r["b"], r["c"]]
        expected = r["tokens"] ? r["tokens"][r["expected"]] : r["expected"]
        if inputs.include?(top) then :input
        elsif top == expected then :expected
        else :other
        end
      end.tally
      [m, metric, pct(tally[:input].to_i, rows.length), pct(tally[:expected].to_i, rows.length),
       pct(tally[:other].to_i, rows.length)]
    end
  end
)

out << "\n## 3. Analogy accuracy by relation (euclidean, inputs excluded)\n\n"
relations = core[models.first].map { |r| r["relation"] }.uniq.sort
out << table(
  ["relation", *models.map { |m| "#{m} top-1" }],
  relations.map do |relation|
    counts = models.map do |m|
      group = core[m].select { |r| r["relation"] == relation }
      pct(group.count { |r| r["euclidean"]["rank"] == 1 }, group.length)
    end
    [relation, *counts]
  end
)

gpt2_by_key = models.include?("gpt2") ? analogy["gpt2"]["analogies"].to_h { |r| [key.call(r), r] } : {}
every_analogy = lambda do |rows|
  table(
    ["relation", "arithmetic", "expected", *models.flat_map { |m| ["#{m} top-1", "rank"] }],
    rows.map do |row|
      cells = models.map do |m|
        source = m == models.first ? row : gpt2_by_key[key.call(row)]
        source ? [show(source["euclidean"]["top1"]), source["euclidean"]["rank"]] : ["-", "-"]
      end
      [row["relation"], "#{row["b"]} - #{row["a"]} + #{row["c"]}", row["expected"], *cells.flatten]
    end
  )
end

out << "\n## 4. Every analogy, both models\n\n"
out << "Euclidean, inputs excluded. `rank` is where the expected word landed.\n\n"
out << every_analogy.call(core[models.first])

unless ruby[models.first].empty?
  out << "\n## 5. The ruby group\n\n"
  out << "Programming-domain analogies, scored apart from the original set "
  out << "because they ask a different question: every word here has to mean "
  out << "its programming sense, which GloVe's news corpus rarely saw. A `-` "
  out << "row means a word had no vector in that model. Euclidean, inputs "
  out << "excluded.\n\n"
  out << every_analogy.call(ruby[models.first])
  out << "\n"
  out << table(
    ["model", "metric", "inputs excluded", "inputs kept", "word-like only", "median rank excl."],
    models.flat_map do |m|
      METRICS.map do |metric|
        scored = ruby[m].map { |r| r[metric] }
        word_like = scored.map { |s| s["rank_word_like"] }.compact
        [m, metric,
         pct(scored.count { |s| s["rank"] == 1 }, scored.length),
         pct(scored.count { |s| s["rank_with_inputs"] == 1 }, scored.length),
         word_like.empty? ? "-" : pct(word_like.count { |r| r == 1 }, word_like.length),
         median(scored.map { |s| s["rank"] })]
      end
    end
  )
end

out << "\n## 6. The plural direction on held-out pairs\n\n"
out << "A pair is separated when the plural scores above the singular. "
out << "`seed` is the direction from `cats - cat` alone; `averaged` is the mean "
out << "of #{direction[models.first]["training"].length} training pairs. No test "
out << "pair was seen by either direction.\n\n"
out << table(
  ["model", "direction", "score", "all pairs", "regular", "irregular"],
  models.flat_map do |m|
    pairs = direction[m]["pairs"]
    forms = pairs.group_by { |p| p["form"] }
    CONDITIONS.flat_map do |condition|
      DIRECTION_METRICS.map do |metric|
        k = "#{condition}_#{metric}"
        counts = ->(group) { pct(group.count { |p| p[k]["separates"] }, group.length) }
        [m, condition, metric, counts.call(pairs),
         counts.call(forms["regular"] || []), counts.call(forms["irregular"] || [])]
      end
    end
  end
)

if models.length > 1
  shared = models.map { |m| direction[m]["pairs"].map(&pair_key).to_set }.reduce(:&)
  out << "\n### The same pairs, both models\n\n"
  out << "#{shared.size} pairs exist in every model. Pairs only one model can "
  out << "answer are dropped here.\n\n"
  out << table(
    ["model", "direction", "score", "shared pairs"],
    models.flat_map do |m|
      pairs = direction[m]["pairs"].select { |p| shared.include?(pair_key.call(p)) }
      CONDITIONS.flat_map do |condition|
        DIRECTION_METRICS.map do |metric|
          k = "#{condition}_#{metric}"
          [m, condition, metric, pct(pairs.count { |p| p[k]["separates"] }, pairs.length)]
        end
      end
    end
  )
end

out << "\n## 7. Pairs the direction gets wrong\n\n"
misses = models.flat_map do |m|
  CONDITIONS.product(DIRECTION_METRICS).flat_map do |condition, metric|
    k = "#{condition}_#{metric}"
    direction[m]["pairs"].reject { |p| p[k]["separates"] }.map do |p|
      [m, condition, metric, "#{p["singular"]} / #{p["plural"]}", p["form"],
       format("%.3f", p[k]["singular"]), format("%.3f", p[k]["plural"])]
    end
  end
end
out << if misses.empty?
         "None.\n"
       else
         table(["model", "direction", "score", "pair", "form", "singular", "plural"], misses)
       end

if models.include?("gpt2")
  out << "\n## 8. Which token stood in for each word (GPT-2)\n\n"
  out << "The policy is: both mid-sentence forms first (` word`, then "
  out << "` Word`), then the line-initial ones. Only words that needed something "
  out << "other than the plain mid-sentence form are listed.\n\n"
  forms = {}
  (analogy["gpt2"]["analogies"] + direction["gpt2"]["pairs"]).each do |row|
    (row["tokens"] || {}).each { |word, token| forms[word] = token }
  end
  unusual = forms.reject { |word, token| token == " #{word}" }.sort
  out << if unusual.empty?
           "Every word resolved to its plain mid-sentence token.\n"
         else
           table(["word", "token used"], unusual.map { |word, token| [word, show(token)] })
         end

  absent = [analogy["gpt2"], direction["gpt2"]]
           .flat_map { |file| file["provenance"]["words_without_a_vector"] || [] }
           .uniq.sort
  unless absent.empty?
    out << "\nWords with no single GPT-2 token, dropped from its runs: "
    out << "#{absent.map { |w| "`#{w}`" }.join(", ")}.\n"
  end
end

if ARGV.include?("--stdout")
  puts out
else
  path = File.join(RESULTS, "tables.md")
  File.write(path, out)
  warn "wrote #{path}"
  puts out
end
