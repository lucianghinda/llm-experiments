#!/usr/bin/env ruby
# frozen_string_literal: true

# Turns results/*.json into results/tables.md.
#
#   ruby word-vector-arithmetic/scripts/report.rb
#   ruby word-vector-arithmetic/scripts/report.rb --stdout   # print, write nothing
#
# EVERY NUMBER IN README.md COMES FROM HERE. Nothing is counted by hand, so a
# claim in the write-up can be re-derived by rerunning this file against the
# committed JSON -- no download, no rescan.
#
# THE HEADLINE IS THE EXCLUSION COLUMN. The same 18 analogies are scored twice.
# "inputs excluded" is what gensim's most_similar reports and what the famous
# claim rests on; "inputs kept" is what the arithmetic actually lands on. The
# gap between those two columns is the finding, so they are always printed
# side by side and never averaged together.

require "json"

EXPERIMENT_DIR = File.expand_path("..", __dir__)
RESULTS = File.join(EXPERIMENT_DIR, "results")
METRICS = %w[euclidean cosine].freeze
CONDITIONS = %w[seed averaged].freeze
DIRECTION_METRICS = %w[dot cosine].freeze

def pct(hits, total)
  return "n/a" if total.zero?

  format("%d/%d (%d%%)", hits, total, (100.0 * hits / total).round)
end

def median(values)
  return "n/a" if values.empty?

  sorted = values.sort
  middle = sorted.length / 2
  value = sorted.length.odd? ? sorted[middle] : ((sorted[middle - 1] + sorted[middle]) / 2.0)
  # %g so an odd-length list reads 1 and an even-length one reads 1.5, rather
  # than the 1 / 1.0 mix that Integer and Float division produce.
  format("%g", value)
end

def table(headers, rows)
  lines = ["| #{headers.join(" | ")} |", "|#{headers.map { "---" }.join("|")}|"]
  rows.each { |row| lines << "| #{row.join(" | ")} |" }
  "#{lines.join("\n")}\n"
end

analogy = JSON.parse(File.read(File.join(RESULTS, "analogy.json")))
direction = JSON.parse(File.read(File.join(RESULTS, "direction.json")))
rows = analogy["analogies"]
pairs = direction["pairs"]

out = +""
out << "<!-- Generated by scripts/report.rb. Do not edit by hand. -->\n\n"
out << "# Tables\n\n"
out << "GloVe #{analogy["provenance"]["entry"]}, "
out << "#{analogy["provenance"]["vocabulary"]} words, "
out << "#{analogy["provenance"]["dimensions"]} dimensions, "
out << "sha256 `#{analogy["provenance"]["table_sha256"][0, 12]}`.\n\n"

out << "## 1. Analogy top-1 accuracy\n\n"
out << "`b - a + c`, ranked against the whole vocabulary. "
out << "Hit means the expected word came first.\n\n"
out << table(
  ["metric", "inputs excluded", "inputs kept", "median rank excl.", "median rank kept"],
  METRICS.map do |metric|
    scored = rows.map { |r| r[metric] }
    [
      metric,
      pct(scored.count { |s| s["rank"] == 1 }, scored.length),
      pct(scored.count { |s| s["rank_with_inputs"] == 1 }, scored.length),
      median(scored.map { |s| s["rank"] }),
      median(scored.map { |s| s["rank_with_inputs"] })
    ]
  end
)

out << "\n## 2. What comes first when the inputs are left in\n\n"
out << "The three input words are `a`, `b`, `c`. If the nearest point to "
out << "`b - a + c` is one of them, the arithmetic did not move far enough to "
out << "leave its own inputs behind.\n\n"
out << table(
  ["metric", "an input word", "the expected word", "something else"],
  METRICS.map do |metric|
    tally = rows.map do |r|
      top = r[metric]["top1_with_inputs"]
      if [r["a"], r["b"], r["c"]].include?(top) then :input
      elsif top == r["expected"] then :expected
      else :other
      end
    end.tally
    [metric, pct(tally[:input].to_i, rows.length), pct(tally[:expected].to_i, rows.length),
     pct(tally[:other].to_i, rows.length)]
  end
)

out << "\n## 3. Analogy accuracy by relation (euclidean, inputs excluded)\n\n"
out << table(
  ["relation", "top-1", "median rank"],
  rows.group_by { |r| r["relation"] }.sort.map do |relation, group|
    [relation, pct(group.count { |r| r["euclidean"]["rank"] == 1 }, group.length),
     median(group.map { |r| r["euclidean"]["rank"] })]
  end
)

out << "\n## 4. Every analogy\n\n"
out << "`rank` is where the expected word landed with the inputs excluded; "
out << "`kept` is the same rank with them left in.\n\n"
out << table(
  ["relation", "arithmetic", "expected", "top-1", "rank", "kept", "top-1 with inputs"],
  rows.map do |r|
    e = r["euclidean"]
    [r["relation"], "#{r["b"]} - #{r["a"]} + #{r["c"]}", r["expected"],
     e["top1"], e["rank"], e["rank_with_inputs"], e["top1_with_inputs"]]
  end
)

out << "\n## 5. The plural direction on held-out pairs\n\n"
out << "A pair is separated when the plural scores above the singular. "
out << "`seed` is the direction from `cats - cat` alone; `averaged` is the mean "
out << "of #{direction["training"].length} training pairs. #{pairs.length} test pairs, none of them seen by "
out << "either direction.\n\n"
forms = pairs.group_by { |p| p["form"] }
out << table(
  ["direction", "score", "all pairs", "regular", "irregular"],
  CONDITIONS.flat_map do |condition|
    DIRECTION_METRICS.map do |metric|
      key = "#{condition}_#{metric}"
      counts = ->(group) { pct(group.count { |p| p[key]["separates"] }, group.length) }
      [condition, metric, counts.call(pairs),
       counts.call(forms["regular"] || []), counts.call(forms["irregular"] || [])]
    end
  end
)

out << "\n## 6. Pairs the direction gets wrong\n\n"
misses = CONDITIONS.product(DIRECTION_METRICS).flat_map do |condition, metric|
  key = "#{condition}_#{metric}"
  pairs.reject { |p| p[key]["separates"] }.map do |p|
    [condition, metric, "#{p["singular"]} / #{p["plural"]}", p["form"],
     format("%.3f", p[key]["singular"]), format("%.3f", p[key]["plural"])]
  end
end
out << if misses.empty?
         "None.\n"
       else
         table(["direction", "score", "pair", "form", "singular", "plural"], misses)
       end

if ARGV.include?("--stdout")
  puts out
else
  path = File.join(RESULTS, "tables.md")
  File.write(path, out)
  warn "wrote #{path} (#{out.lines.length} lines)"
  puts out
end
